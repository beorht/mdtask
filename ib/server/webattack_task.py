def _has(cmd, subs):
    s = " ".join(cmd["argv"]).lower()
    return any(x in s for x in subs)


def _grep(env, *subs):
    return env.ran("grep", lambda c: _has(c, subs))


def _path_eq(value, full):
    v = value.strip().strip("'\"").rstrip("/")
    return v == full or v == full.rsplit("/", 1)[-1] or v.lstrip("/") == full.lstrip("/")


def _base(path):
    return path.rsplit("/", 1)[-1]


