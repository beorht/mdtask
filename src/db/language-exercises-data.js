// order_index is a single sequence per language (0..N-1), in the topic order defined
// above, so it can be a plain unique column instead of a (topic, position) pair.
function withOrder(list, language) {
  return list.map((e, i) => ({
    id: `${language}-${e.topic}-${i}`,
    language,
    orderIndex: i,
    topicLabel: TOPIC_LABELS[e.topic],
    ...e,
  }));
}

const exercises = [...withOrder(python, 'python'), ...withOrder(javascript, 'javascript')];

