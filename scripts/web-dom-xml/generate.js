const RESTRICTIONS = ['range', 'enumeration', 'pattern'];
const MIN_RECORDS = [8, 9, 10, 11, 12];

// Вариант студента: детерминированно из его id.
function variantFor(studentId, name = '', login = studentId) {
  const seed = hash(String(studentId));
  const theme = THEMES[seed % THEMES.length];
  const restriction = RESTRICTIONS[(seed >>> 3) % RESTRICTIONS.length];
  const minRecords = MIN_RECORDS[(seed >>> 6) % MIN_RECORDS.length];
  // Поле поиска на первой странице — название, вторичное текстовое поле или перечисление.
  const searchChoices = [theme.name, theme.text.label, theme.enumF.label];
  const searchField = searchChoices[(seed >>> 9) % searchChoices.length];
  return { studentId, name, login, theme, restriction, minRecords, searchField };
}

// Человеческое описание обязательного ограничения XSD.
function restrictionText(v) {
  if (v.restriction === 'range') {
    return `поле «${v.theme.numF.label}» — целое число в диапазоне от ${v.theme.numF.min} до ${v.theme.numF.max} ` +
      `(xs:minInclusive и xs:maxInclusive)`;
  }
  if (v.restriction === 'enumeration') {
    return `поле «${v.theme.enumF.label}» — только одно из значений: ${v.theme.enumF.values.join(', ')} (xs:enumeration)`;
  }
  return 'поле «артикул» — по шаблону: две заглавные латинские буквы, дефис, три цифры (например, AB-017) (xs:pattern)';
}

// Текст задания для студента. Без готового кода: только требования, таблицы, чек-лист.
function statement(v) {
  const t = v.theme;
  const fields = [
    ['id', 'целое', 'уникальный номер записи'],
    [t.name, 'строка', `${t.item} — основное название`],
    [t.text.label, 'строка', t.text.note],
    [t.enumF.label, 'строка', `одно из: ${t.enumF.values.join(', ')}`],
    [t.numF.label, 'целое', `${t.numF.unit}, от ${t.numF.min} до ${t.numF.max}`],
    ['описание', 'строка', '1–2 предложения'],
    ['изображение', 'строка', 'имя файла рядом с сайтом или ссылка'],
  ];
  if (v.restriction === 'pattern') fields.splice(1, 0, ['артикул', 'строка', 'код по шаблону AB-017']);
  const fieldRows = fields.map(([f, ty, note]) => `| ${f} | ${ty} | ${note} |`).join('\n');
  return `# Каталог на XML и DOM (двухстраничный сайт)

Вы делаете сайт из двух страниц. Все данные каталога хранятся в XML-файле, а страницы
строятся из этих данных средствами DOM (JavaScript). Готового кода в задании нет — весь
код вы пишете сами.

## Ваш вариант

- **Тема каталога:** ${t.catalog} (каждая запись — ${t.item}).
- **Поиск на первой странице** — по полю «${v.searchField}».
- **Записей в каталоге** — не менее ${v.minRecords}.
- **Обязательное ограничение в XSD:** ${restrictionText(v)}.
- **Личный маркёр:** первой строкой в \`data.xml\` поставьте комментарий \`<!-- автор: ${v.login} -->\`.

## Поля одной записи (${t.item})

Структуру XML вы проектируете сами по этой таблице (имена тегов — на ваш выбор):

| Поле | Тип | Примечание |
|------|-----|-----------|
${fieldRows}

## Что сдавать (два файла по отдельности)

1. **Код сайта** — одним архивом **site.zip** со всеми файлами сайта:

| Файл в архиве | Назначение |
|------|-----------|
| index.html | Страница 1 — каталог (список записей) |
| item.html | Страница 2 — карточка одной записи |
| style.css | Оформление обеих страниц |
| script.js | Вся логика через DOM |
| data.xml | Данные каталога (не менее ${v.minRecords} записей) |

2. **Схему** — отдельным файлом **schema.xsd** (XSD-схема, которой соответствует data.xml).

На странице задания два поля загрузки: «Код сайта (архив)» и «Схема XSD (schema.xsd)».
Загрузите в них оба файла и нажмите «Сдать».

## Что должно работать

**Страница 1 — каталог (index.html).**
- script.js загружает data.xml (через fetch и DOMParser или XMLHttpRequest) и разбирает его.
- Список записей строится **средствами DOM** (создание элементов и вставка в страницу),
  а не записан заранее в HTML.
- Есть поиск/фильтр по полю «${v.searchField}»: при вводе список обновляется.
- По клику на запись — переход на страницу карточки с передачей номера записи в адресе,
  например item.html?id=3.

**Страница 2 — карточка (item.html).**
- script.js читает номер записи из адреса (id в строке запроса), находит эту запись в data.xml
  и показывает все её поля — тоже средствами DOM.
- Есть ссылка «назад» в каталог.

**Общее.**
- Только средства DOM и обычный JavaScript, без сторонних библиотек и фреймворков.
- Оформление в style.css, обе страницы связаны навигацией.

## XSD-схема (schema.xsd)

- Опишите структуру data.xml: корневой элемент, повторяющийся элемент записи и все поля.
- Укажите типы полей (целое число — xs:integer, строка — xs:string).
- Обязательно добавьте ограничение из вашего варианта: ${restrictionText(v)}.
- Убедитесь, что data.xml проходит валидацию по schema.xsd (онлайн-валидатор XML/XSD или
  команда xmllint с ключом schema). Невалидный XML считается ошибкой.

## Как сдавать

Загрузите два файла в два поля на странице задания: архив кода **site.zip** (без схемы) и
отдельно файл схемы **schema.xsd**.

## Чек-лист самопроверки

- [ ] data.xml проходит валидацию по schema.xsd;
- [ ] в data.xml не менее ${v.minRecords} записей и первой строкой стоит маркёр с вашим логином;
- [ ] список на странице 1 строится из XML средствами DOM, а не записан в HTML;
- [ ] поиск по полю «${v.searchField}» работает;
- [ ] переход на карточку по номеру записи (id в адресе) работает и показывает все поля;
- [ ] обе страницы открываются и связаны навигацией.
`;
}

