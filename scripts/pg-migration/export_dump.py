#!/usr/bin/env python3
"""
Копия базы mdtask (SQLite) в виде SQL-дампа для PostgreSQL, зашифрованного шифром Цезаря.

Исходная база не изменяется: скрипт делает снимок через SQLite backup API (учитывает WAL,
работающий сервер останавливать не нужно) и читает только снимок.

    python3 scripts/pg-migration/export_dump.py                    # ключ сгенерируется
    python3 scripts/pg-migration/export_dump.py --key 113          # свой ключ 1–255
    python3 scripts/pg-migration/export_dump.py --db data/mdtask.db --out-dir data/migration

Результат (каталог data/migration/ не попадает в git):
    mdtask-<время>.pgsql.caesar   — зашифрованный дамп
    caesar.key                    — ключ (если он сгенерирован); права 600. Передавайте
                                    его отдельно от файла дампа.

Дамп — один транзакционный скрипт для psql: таблицы, данные, счётчики автоинкремента,
индексы, CHECK и внешние ключи (NOT VALID — существующие строки не перепроверяются),
и проверка числа строк в каждой таблице перед COMMIT: при расхождении всё откатывается.
Типы: INTEGER → BIGINT (столбцы, где фактически лежат не только целые, — TEXT),
REAL → DOUBLE PRECISION, BLOB → BYTEA, остальное → TEXT; одиночный INTEGER PRIMARY KEY
становится identity-столбцом.
"""

import argparse
import datetime as dt
import os
import re
import secrets
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import caesar  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BATCH = 200


def q(name):
    return '"' + name.replace('"', '""') + '"'


def literal(value, pg_type):
    if value is None:
        return "NULL"
    if isinstance(value, bytes):
        return "'\\x" + value.hex() + "'::bytea"
    if pg_type in ("BIGINT", "DOUBLE PRECISION") and isinstance(value, (int, float)):
        return repr(value) if isinstance(value, float) else str(value)
    text = str(value)
    if "\x00" in text:
        raise ValueError("в тексте есть символ NUL — PostgreSQL его не принимает")
    return "'" + text.replace("'", "''") + "'"


def column_type(conn, table, column, declared):
    decl = (declared or "").upper()
    kinds = {r[0] for r in conn.execute(f"SELECT DISTINCT typeof({q(column)}) FROM {q(table)}")} - {"null"}
    if "INT" in decl and kinds <= {"integer"}:
        return "BIGINT"
    if any(k in decl for k in ("REAL", "FLOA", "DOUB")) and kinds <= {"integer", "real"}:
        return "DOUBLE PRECISION"
    if "BLOB" in decl and kinds <= {"blob"}:
        return "BYTEA"
    return "TEXT"


def check_clauses(create_sql):
    """Выражения CHECK (...) из текста CREATE TABLE, со сбалансированными скобками."""
    out = []
    for m in re.finditer(r"\bCHECK\s*\(", create_sql, re.I):
        depth, i = 0, m.end() - 1
        start = i
        in_str = False
        while i < len(create_sql):
            c = create_sql[i]
            if c == "'":
                in_str = not in_str
            elif not in_str and c == "(":
                depth += 1
            elif not in_str and c == ")":
                depth -= 1
                if depth == 0:
                    out.append(create_sql[start + 1:i].strip())
                    break
            i += 1
    return out


def build_dump(conn, source):
    tables = [r[0] for r in conn.execute(
        "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid")]
    create, data, after, constraints, counts = [], [], [], [], {}

    for t in tables:
        info = conn.execute(f"SELECT name, type, \"notnull\", dflt_value, pk FROM pragma_table_info({literal(t, 'TEXT')})").fetchall()
        pk = [r[0] for r in sorted((r for r in info if r[4]), key=lambda r: r[4])]
        types = {name: column_type(conn, t, name, decl) for name, decl, *_ in info}
        cols = []
        for name, decl, notnull, default, _pk in info:
            line = f"  {q(name)} {types[name]}"
            if pk == [name] and types[name] == "BIGINT":
                line += " GENERATED BY DEFAULT AS IDENTITY"
                after.append(f"  PERFORM setval(pg_get_serial_sequence({literal(q(t), 'TEXT')}, {literal(name, 'TEXT')}), "
                             f"COALESCE((SELECT MAX({q(name)}) FROM {q(t)}), 0) + 1, false);")
            if notnull:
                line += " NOT NULL"
            if default is not None:
                line += f" DEFAULT {default}"
            cols.append(line)
        if pk:
            cols.append(f"  PRIMARY KEY ({', '.join(q(c) for c in pk)})")
        create.append(f"CREATE TABLE {q(t)} (\n" + ",\n".join(cols) + "\n);")

        names = [r[0] for r in info]
        rows = conn.execute(f"SELECT {', '.join(q(c) for c in names)} FROM {q(t)} ORDER BY rowid").fetchall()
        counts[t] = len(rows)
        for i in range(0, len(rows), BATCH):
            values = ",\n".join("(" + ", ".join(literal(v, types[c]) for v, c in zip(row, names)) + ")" for row in rows[i:i + BATCH])
            data.append(f"INSERT INTO {q(t)} ({', '.join(q(c) for c in names)}) VALUES\n{values};")

        for idx_name, unique, origin in conn.execute(f"SELECT name, \"unique\", origin FROM pragma_index_list({literal(t, 'TEXT')})"):
            if origin == "pk":
                continue
            idx_cols = [r[0] for r in conn.execute(f"SELECT name FROM pragma_index_info({literal(idx_name, 'TEXT')}) ORDER BY seqno")]
            pg_name = idx_name if not idx_name.startswith("sqlite_autoindex") else f"{t}_{'_'.join(idx_cols)}_key"
            constraints.append(f"CREATE {'UNIQUE ' if unique else ''}INDEX {q(pg_name)} ON {q(t)} ({', '.join(q(c) for c in idx_cols)});")

        create_sql = conn.execute("SELECT sql FROM sqlite_master WHERE name = ?", (t,)).fetchone()[0]
        for n, expr in enumerate(check_clauses(create_sql), 1):
            constraints.append(f"ALTER TABLE {q(t)} ADD CONSTRAINT {q(f'{t}_check_{n}')} CHECK ({expr}) NOT VALID;")
        fks = {}
        for _id, _seq, ref, frm, to, on_update, on_delete, _m in conn.execute(f"SELECT * FROM pragma_foreign_key_list({literal(t, 'TEXT')})"):
            fk = fks.setdefault(_id, {"ref": ref, "from": [], "to": [], "upd": on_update, "del": on_delete})
            fk["from"].append(frm)
            fk["to"].append(to)
        for n, fk in sorted(fks.items()):
            to_cols = fk["to"] if all(fk["to"]) else ["id"] * len(fk["from"])
            rule = "".join(f" ON {kind} {act}" for kind, act in (("UPDATE", fk["upd"]), ("DELETE", fk["del"])) if act and act != "NO ACTION")
            constraints.append(f"ALTER TABLE {q(t)} ADD CONSTRAINT {q(f'{t}_fk_{n}')} FOREIGN KEY ({', '.join(q(c) for c in fk['from'])}) "
                               f"REFERENCES {q(fk['ref'])} ({', '.join(q(c) for c in to_cols)}){rule} NOT VALID;")

    checks = "\n".join(
        f"  IF (SELECT COUNT(*) FROM {q(t)}) <> {n} THEN RAISE EXCEPTION 'таблица {t}: ожидалось {n} строк'; END IF;" for t, n in counts.items())
    header = [
        "-- Дамп базы mdtask для PostgreSQL",
        f"-- Источник: {source}",
        f"-- Создан: {dt.datetime.now().astimezone().isoformat(timespec='seconds')}",
        "-- Строк: " + ", ".join(f"{t} {n}" for t, n in counts.items()),
        "-- Загружать в пустую базу: psql -v ON_ERROR_STOP=1 -f <файл>",
        "",
        "SET client_encoding = 'UTF8';",
        "SET standard_conforming_strings = on;",
        "BEGIN;",
        "",
    ]
    sequences = ["DO $$\nBEGIN\n" + "\n".join(after) + "\nEND\n$$;"] if after else []
    body = create + [""] + data + [""] + sequences + [""] + constraints + ["", "DO $$\nBEGIN\n" + checks + "\nEND\n$$;", "", "COMMIT;", ""]
    return "\n".join(header + body).encode("utf-8"), counts


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=os.path.join(ROOT, "data", "mdtask.db"))
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "data", "migration"))
    ap.add_argument("--key", type=int, help="ключ шифра 1–255 (по умолчанию — случайный, сохраняется в caesar.key)")
    args = ap.parse_args()

    if not os.path.exists(args.db):
        sys.exit(f"нет файла базы: {args.db}")
    key = caesar.check_key(args.key) if args.key is not None else secrets.randbelow(255) + 1

    # Снимок через backup API: исходный файл открывается только на чтение.
    source = sqlite3.connect(f"file:{os.path.abspath(args.db)}?mode=ro", uri=True)
    snapshot = sqlite3.connect(":memory:")
    source.backup(snapshot)
    source.close()
    dump, counts = build_dump(snapshot, os.path.relpath(args.db, ROOT))
    snapshot.close()

    os.makedirs(args.out_dir, exist_ok=True)
    os.chmod(args.out_dir, 0o700)
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    out = os.path.join(args.out_dir, f"mdtask-{stamp}.pgsql.caesar")
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(caesar.encrypt(dump, key))
    print(f"Дамп: {os.path.relpath(out, ROOT)} ({len(dump) // 1024} КБ до шифрования)")
    print("Таблиц:", len(counts), "| строк:", sum(counts.values()))
    if args.key is None:
        key_path = os.path.join(args.out_dir, "caesar.key")
        fd = os.open(key_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(f"{key}\n")
        print(f"Ключ шифра сохранён в {os.path.relpath(key_path, ROOT)} (права 600) — передавайте его отдельно от дампа.")


if __name__ == "__main__":
    main()
